import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const sourceDir = path.resolve(scriptDir, "../opencli-adapters/chatgpt");
const targetDir = path.join(os.homedir(), ".opencli", "clis", "chatgpt");
const filenames = ["submit-file-core.js", "submit-file.js", "oracle-wait.js"];
const replace = process.argv.includes("--replace");

const modelSelectionModule = await import(
  pathToFileURL(path.resolve(scriptDir, "../dist/src/browser/actions/modelSelection.js")).href
);
const thinkingTimeModule = await import(
  pathToFileURL(path.resolve(scriptDir, "../dist/src/browser/actions/thinkingTime.js")).href
);
const generatedPickerPath = path.join(targetDir, "oracle-picker.generated.js");
const generatedPickerSource = [
  "// Generated by Oracle. Re-run the adapter installer after updating Oracle.",
  `export const ORACLE_GPT56_SOL_MODEL_EXPRESSION = ${JSON.stringify(modelSelectionModule.buildModelSelectionExpression("GPT-5.6 Sol", "select"))};`,
  `export const ORACLE_PRO_THINKING_EXPRESSION = ${JSON.stringify(thinkingTimeModule.buildThinkingTimeExpression("pro", "GPT-5.6 Sol"))};`,
  "",
].join("\n");
const installEntries = await Promise.all(
  filenames.map(async (filename) => ({
    targetPath: path.join(targetDir, filename),
    source: await fs.readFile(path.join(sourceDir, filename), "utf8"),
  })),
);
installEntries.push({ targetPath: generatedPickerPath, source: generatedPickerSource });

await fs.mkdir(targetDir, { recursive: true });
const inspectedEntries = await Promise.all(
  installEntries.map(async (entry) => ({
    ...entry,
    existing: await fs.readFile(entry.targetPath, "utf8").catch(() => null),
  })),
);
for (const entry of inspectedEntries) {
  if (entry.existing !== null && entry.existing !== entry.source && !replace) {
    throw new Error(
      `${entry.targetPath} already exists with different content; inspect it or rerun with --replace.`,
    );
  }
}
for (const entry of inspectedEntries) {
  if (entry.existing === entry.source) {
    process.stdout.write(`current ${entry.targetPath}\n`);
    continue;
  }
  const temporaryPath = `${entry.targetPath}.${process.pid}.tmp`;
  await fs.writeFile(temporaryPath, entry.source, {
    encoding: "utf8",
    mode: 0o644,
    flag: "wx",
  });
  await fs.rename(temporaryPath, entry.targetPath);
  await fs.chmod(entry.targetPath, 0o644);
  process.stdout.write(`installed ${entry.targetPath}\n`);
}
